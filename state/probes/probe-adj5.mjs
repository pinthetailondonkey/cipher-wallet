import { hex } from '@scure/base';
import { parseBlock } from '/home/aegis/cipher-wallet/src/monero/block.js';
import { ownOutputsInBlock } from '/home/aegis/cipher-wallet/src/monero/ownOutputs.js';
import { transactionPublicKey } from '/home/aegis/cipher-wallet/src/monero/scan.js';
import { keyDerivation, decodePoint, encodePoint, bytesToNumberLE, scReduce32 } from '/home/aegis/cipher-wallet/src/monero/keys.js';
import { derivationToScalar } from '/home/aegis/cipher-wallet/src/monero/ringct.js';
const F=(n)=>JSON.parse(readFileSync('/home/aegis/cipher-wallet/test/fixtures/'+n,'utf8'));
const bx=(s)=>Uint8Array.from(Buffer.from(String(s).replace(/\s+/g,''),'hex'));
const G=decodePoint(bx('58666666666666666666666666666666 66666666666666666666666666666666'));
const blob=bx(F('monero-block-3796965.json').block.blob);
const blk=parseBlock(blob);
const TXS=F('monero-block-3796965-txs.json').txs.map(t=>bx(t.asHex));
const mtx=blk.minerTx; console.log('miner outputs',mtx.outputs.length,'rctType',mtx.rctType);
const txPub=transactionPublicKey(mtx.extra);
const vs=scReduce32(Uint8Array.from({length:32},(_,i)=>(i*7+2)&0xff));
